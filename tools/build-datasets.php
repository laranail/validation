<?php

declare(strict_types=1);

/**
 * Builds the bundled I18n datasets in `resources/data/` from the committed
 * registry snapshots in `tools/data-sources/`.
 *
 *   php tools/build-datasets.php            write the datasets
 *   php tools/build-datasets.php --check    exit 1 if a file on disk differs
 *
 * ## Why generate rather than type
 *
 * A code list typed by hand drifts the moment a registry moves (ISO 4217
 * retired four currencies between 2016 and 2023 alone), and nothing fails
 * when it does. Generating from a committed snapshot of the official
 * registry makes the data a pure function of a traceable input, and the
 * `--check` test in the suite fails the build if the two ever diverge —
 * the same discipline `laranail/atlas` applies to its country dataset.
 *
 * ## Sources (committed snapshots, provenance in each file)
 *
 * - `iso-4217-list-one.xml` — the official ISO 4217 "List One" published by
 *   SIX Financial Information (the ISO 4217 maintenance agency); the
 *   `Pblshd` attribute carries the publication date.
 * - `iso-639-2.txt` — the ISO 639-2 registry published by the Library of
 *   Congress (the ISO 639-2 registration authority); column 3 carries the
 *   ISO 639-1 alpha-2 code where one is assigned.
 * - `iso-3166.txt` — alpha-2/alpha-3 pairs cross-checked between two
 *   agreeing Simtabi sources (see the file's header).
 *
 * `currency-symbols.txt` is the one output NOT covered by `--check`: it is
 * rendered from the local ICU's CLDR data (`ICUDATA-curr`), which varies by
 * ICU version. Regenerate it deliberately; the committed file is the record.
 */
$root = dirname(__DIR__);
$sources = $root . '/tools/data-sources';
$out = $root . '/resources/data';
$check = in_array('--check', $argv, true);

/** @return array{string, string} name => content pairs, checkable ones only */
function buildCheckable(string $sources): array
{
    // --- ISO 3166 -----------------------------------------------------------
    $alpha2 = [];
    $alpha3 = [];

    foreach (explode("\n", (string) file_get_contents($sources . '/iso-3166.txt')) as $line) {
        $line = trim($line);

        if ($line === '' || str_starts_with($line, '#')) {
            continue;
        }

        [$a2, $a3] = explode(' ', $line);
        $alpha2[] = $a2;

        if ($a3 !== '-') {
            $alpha3[] = $a3;
        }
    }

    sort($alpha2);
    sort($alpha3);

    // --- ISO 4217 -----------------------------------------------------------
    $xml = new SimpleXMLElement((string) file_get_contents($sources . '/iso-4217-list-one.xml'));
    $published = (string) $xml['Pblshd'];
    $currencies = [];

    foreach ($xml->CcyTbl->CcyNtry as $entry) {
        // Territories with "no universal currency" carry no Ccy element.
        if (! isset($entry->Ccy)) {
            continue;
        }

        $code = (string) $entry->Ccy;
        $numeric = isset($entry->CcyNbr) ? (string) $entry->CcyNbr : '-';
        $currencies[$code] = $numeric;
    }

    ksort($currencies);

    // --- ISO 639-1 ----------------------------------------------------------
    $languages = [];
    $registry = (string) file_get_contents($sources . '/iso-639-2.txt');
    $registry = preg_replace('/^\xEF\xBB\xBF/', '', $registry) ?? $registry;

    foreach (explode("\n", $registry) as $line) {
        $columns = explode('|', trim($line));

        if (count($columns) >= 3 && $columns[2] !== '') {
            $languages[$columns[2]] = true;
        }
    }

    $languages = array_keys($languages);
    sort($languages);

    // --- Render -------------------------------------------------------------
    $files = [];

    $files['iso-3166-alpha2.txt'] = "# ISO 3166-1 alpha-2 country codes. GENERATED by tools/build-datasets.php\n"
        . "# from tools/data-sources/iso-3166.txt — do not edit by hand.\n"
        . implode("\n", $alpha2) . "\n";

    $files['iso-3166-alpha3.txt'] = "# ISO 3166-1 alpha-3 country codes. GENERATED by tools/build-datasets.php\n"
        . "# from tools/data-sources/iso-3166.txt — do not edit by hand.\n"
        . implode("\n", $alpha3) . "\n";

    $lines = [];

    foreach ($currencies as $code => $numeric) {
        $lines[] = $code . ' ' . $numeric;
    }

    $files['iso-4217.txt'] = "# ISO 4217 currency codes (alpha, numeric). GENERATED by\n"
        . "# tools/build-datasets.php from the official List One published {$published}\n"
        . "# by SIX Financial Information — do not edit by hand.\n"
        . implode("\n", $lines) . "\n";

    $files['iso-639-1.txt'] = "# ISO 639-1 language codes. GENERATED by tools/build-datasets.php from\n"
        . "# the Library of Congress ISO 639-2 registry — do not edit by hand.\n"
        . implode("\n", $languages) . "\n";

    return $files;
}

/** Distinct CLDR currency symbols (en locale) that differ from their code. */
function buildSymbols(string $sources): string
{
    $xml = new SimpleXMLElement((string) file_get_contents($sources . '/iso-4217-list-one.xml'));
    $codes = [];

    foreach ($xml->CcyTbl->CcyNtry as $entry) {
        if (isset($entry->Ccy)) {
            $codes[(string) $entry->Ccy] = true;
        }
    }

    $bundle = ResourceBundle::create('en', 'ICUDATA-curr', false);
    $table = $bundle?->get('Currencies');
    $symbols = [];

    foreach (array_keys($codes) as $code) {
        $row = $table?->get($code);
        $symbol = $row?->get(0);

        if (is_string($symbol) && $symbol !== $code) {
            $symbols[$symbol] = true;
        }
    }

    $symbols = array_keys($symbols);
    sort($symbols);

    return "# CLDR currency symbols (en locale) for the ISO 4217 codes, one per\n"
        . "# line. GENERATED by tools/build-datasets.php from the local ICU —\n"
        . "# symbol renderings vary by ICU version, so this file is exempt from\n"
        . "# --check; regenerate deliberately and review the diff.\n"
        . implode("\n", $symbols) . "\n";
}

$files = buildCheckable($sources);

if ($check) {
    $stale = [];

    foreach ($files as $name => $content) {
        if ((string) @file_get_contents($out . '/' . $name) !== $content) {
            $stale[] = $name;
        }
    }

    if ($stale !== []) {
        fwrite(STDERR, 'Stale datasets (regenerate with `php tools/build-datasets.php`): '
            . implode(', ', $stale) . "\n");
        exit(1);
    }

    echo "Datasets match their sources.\n";
    exit(0);
}

$files['currency-symbols.txt'] = buildSymbols($sources);

foreach ($files as $name => $content) {
    file_put_contents($out . '/' . $name, $content);
    echo "wrote resources/data/{$name}\n";
}
